"""Builds the gust and humidity corrections (src/domain/correction/moreTables.ts) and validates them.

Shipped, for any place (verified results/wind_summary.json, rh_summary.json):
  - Hourly gusts: national additive bias by lead (0, 1 day) x season x standard-time hour, smoothed across seasons.
    (Lead 1 is measured on ICON alone: Open-Meteo keeps no ECMWF previous-day gusts.)
  - Daily maximum gust: national scale factor by lead.
  - Humidity: ICON weight 0.8 for today..day 2 (0.6 after), plus a national additive bias by lead x season x hour.
Mean wind speed is left alone (a national correction gained ~1%).
Validation is leave-one-station-out: fitted on the training years without the scored station, scored on the test year.
"""
import json
import sys

import numpy as np
import pandas as pd

sys.argv = ["x"]
import build_correction as bc
import verify_rh as vr
import verify_temp as v
import verify_wind as vw

SEASONS = bc.SEASONS
OUT_TS = bc.OUT_TS.parent / "moreTables.ts"


def prep(df):
    std = df.time + pd.Timedelta(hours=2)
    df["hour"], df["season"], df["doy"] = std.dt.hour, std.dt.month.map(v.SEASON), std.dt.dayofyear
    df["day"] = std.dt.normalize()
    return df


def loso_smooth(tr, te, e_tr):
    """Smoothed season x hour table without each held-out station: the correction a place without a station gets."""
    sums = e_tr.groupby([tr.station_id, tr.season, tr.hour]).agg(["sum", "count"])
    tot = sums.groupby(level=[1, 2]).sum()
    sw = bc.season_weights(te.doy.to_numpy())
    out = np.full(len(te), np.nan)
    for s in te.station_id.unique():
        m = (te.station_id == s).to_numpy()
        t = tot.sub(sums.loc[s], fill_value=0) if s in sums.index.get_level_values(0) else tot
        tab = (t["sum"] / t["count"]).unstack().reindex(SEASONS).to_numpy()
        out[m] = bc.smooth_bias(tab, sw[m], te.hour[m].to_numpy())
    return out


def full_table(df, e):
    return e.groupby([df.season, df.hour]).mean().unstack().reindex(SEASONS).to_numpy()


def main():
    res, tables = {}, {}
    # --- gusts
    obs = pd.read_parquet(v.OBS, columns=["time", "station_id", "ws_gust", "rh"])
    obs["time"] = pd.to_datetime(obs["time"], utc=True).dt.tz_localize(None)
    g = prep(vw.load("gust").merge(obs[["time", "station_id", "ws_gust"]], on=["station_id", "time"]).dropna(subset=["ws_gust"]))
    g["o"] = g.ws_gust * vw.KMH
    g["f_l0"] = 0.6 * g.icon_l0 + 0.4 * g.ecmwf_l0
    g["f_l1"] = g.icon_l1  # the only lead-1 gust Open-Meteo keeps
    gust_tabs, gust_scale = [], []
    for l in ("l0", "l1"):
        d = g.dropna(subset=[f"f_{l}"])
        tr, te = d[d.time < v.SPLIT], d[d.time >= v.SPLIT]
        b = loso_smooth(tr, te, tr[f"f_{l}"] - tr.o)
        raw = (te[f"f_{l}"] - te.o).abs().mean()
        cor = (te[f"f_{l}"] - np.nan_to_num(b) - te.o).abs().mean()
        gust_tabs.append(-full_table(d, d[f"f_{l}"] - d.o))
        dm = d.groupby(["station_id", "day"]).agg(o=("o", "max"), f=(f"f_{l}", "max"), n=("o", "count")).reset_index()
        dm = dm[dm.n >= 22]
        dtr, dte = dm[dm.day < v.SPLIT], dm[dm.day >= v.SPLIT]
        s = dtr.groupby("station_id").agg(o=("o", "sum"), f=("f", "sum"))
        k = ((s.o.sum() - s.o) / (s.f.sum() - s.f)).rename("k")
        t = dte.join(k, on="station_id")
        gust_scale.append(round(float(dm.o.sum() / dm.f.sum()), 3))
        res[f"gust_{l}"] = {"hourly_raw": round(float(raw), 3), "hourly_corrected": round(float(cor), 3),
                            "daily_max_raw": round(float((dte.f - dte.o).abs().mean()), 3),
                            "daily_max_scaled": round(float((t.f * t.k - t.o).abs().mean()), 3)}
        print("gust", l, res[f"gust_{l}"])
    # --- humidity
    h = prep(vr.load_pass2().merge(obs[["time", "station_id", "rh"]], on=["station_id", "time"]).dropna(subset=["rh"]))
    rh_tabs = []
    for l in ("l0", "l1"):
        d = h.dropna(subset=[f"icon_{l}", f"ecmwf_{l}"]).copy()
        d["app"] = 0.6 * d[f"icon_{l}"] + 0.4 * d[f"ecmwf_{l}"]
        d["f"] = 0.8 * d[f"icon_{l}"] + 0.2 * d[f"ecmwf_{l}"]
        tr, te = d[d.time < v.SPLIT], d[d.time >= v.SPLIT]
        b = loso_smooth(tr, te, tr.f - tr.rh)
        res[f"rh_{l}"] = {"app": round(float((te.app - te.rh).abs().mean()), 3),
                          "new_weight": round(float((te.f - te.rh).abs().mean()), 3),
                          "new_weight_plus_table": round(float((np.clip(te.f - np.nan_to_num(b), 0, 100) - te.rh).abs().mean()), 3)}
        rh_tabs.append(-full_table(d, d.f - d.rh))
        print("rh", l, res[f"rh_{l}"])
    json.dump(res, open(v.OUT / "correction_more_validation.json", "w"), indent=1)

    def arr3(tabs, fmt):
        return "".join("  [\n" + "".join("    [" + ", ".join(fmt.format(x) for x in row) + "],\n" for row in t) + "  ],\n" for t in tabs)
    OUT_TS.write_text(f"""// Generated by research/verification/build_correction_more.py — do not edit by hand.
// From IMS stations against Open-Meteo's past forecasts, 2024 to 2026 (gusts {g.station_id.nunique()} stations, humidity {h.station_id.nunique()}).
// Tables are [lead][season][hour of local standard time, UTC+2]; leads 0 and 1 day ahead (later days use day 1).

/** km/h to ADD to the blended hourly gust (lead 1 measured on ICON alone: Open-Meteo keeps no ECMWF previous-day gusts). */
export const GUST_ADD: readonly (readonly (readonly number[])[])[] = [
{arr3(gust_tabs, "{:.1f}")}]

/** Factor for the blended daily maximum gust, per lead (0, 1 day; later days use day 1). */
export const DAILY_GUST_SCALE = [{", ".join(f"{x:.3f}" for x in gust_scale)}] as const

/** Percentage points of relative humidity to ADD to the blend (ICON 0.8 for today..day 2, 0.6 after). */
export const HUMIDITY_ADD: readonly (readonly (readonly number[])[])[] = [
{arr3(rh_tabs, "{:.1f}")}]
""")
    print("wrote", OUT_TS)


if __name__ == "__main__":
    main()
