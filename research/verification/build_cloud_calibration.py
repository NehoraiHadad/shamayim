"""Export a ground-trained cloud correction for the two hourly Open-Meteo models.

Input is the paired IMS observer/Previous Runs CSV described in README.md.
Requires numpy, pandas and scikit-learn 1.8. Only the latest forecast is used.
"""

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import HistGradientBoostingRegressor

HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parents[1] / "src/domain/correction/cloudTables.ts"
FIELDS = [f"{model}_{field}" for model in ("icon", "ifs") for field in ("total", "low", "mid", "high", "rain")]
FEATURES = [*FIELDS, "low_shift", "total_gap", "low_gap", "long", "day"]


def smoothstep(low, high, value):
    t = np.clip((value - low) / (high - low), 0, 1)
    return t * t * (3 - 2 * t)


def features(rows):
    total_gap = rows.icon_total - rows.ifs_total
    low_gap = rows.icon_low - rows.ifs_low
    low_excess = np.minimum(np.maximum(low_gap, 0), np.maximum(total_gap, 0))
    influence = (1 - smoothstep(5, 15, rows.ifs_total)) * smoothstep(15, 30, total_gap)
    influence *= smoothstep(0.55, 0.80, low_excess / np.maximum(total_gap, 1))
    return rows.assign(low_shift=0.4 * low_excess * influence, total_gap=total_gap, low_gap=low_gap,
                       long=0, day=pd.to_datetime(rows.time).dt.hour.between(7, 14).astype(int))[FEATURES]


def train(rows, x, field, target):
    blend = 0.4 * rows[f"icon_{field}"] + 0.6 * rows[f"ifs_{field}"]
    model = HistGradientBoostingRegressor(loss="absolute_error", learning_rate=0.08, max_iter=40,
                                          max_leaf_nodes=5, max_depth=3, l2_regularization=15,
                                          min_samples_leaf=45, random_state=12)
    model.fit(x, rows[target] - blend)
    return model


def export_model(model, x):
    trees = []
    for (predictor,) in model._predictors:
        trees.append([
            float(n["value"]) if n["is_leaf"] else [
                int(n["feature_idx"]), float(n["num_threshold"]), int(n["left"]), int(n["right"]),
            ]
            for n in predictor.nodes
        ])
    bias = float(model._baseline_prediction.item())

    def predict(row):
        corrections = bias
        for tree in trees:
            node = tree[0]
            while isinstance(node, list):
                feature, threshold, left, right = node
                node = tree[left if row[feature] <= threshold else right]
            corrections += node
        return corrections

    # The app falls back to the base blend for incomplete or invalid model fields.
    np.testing.assert_allclose([predict(row) for row in x.to_numpy()], model.predict(x), atol=1e-10)
    compact = [json.dumps(tree, separators=(",", ":"), allow_nan=False) + "," for tree in trees]
    return f"{{ bias: {bias}, trees: [\n    " + "\n    ".join(compact) + "\n  ] }"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("samples", type=Path)
    args = parser.parse_args()
    rows = pd.read_csv(args.samples).query("lead == 0").dropna(subset=[*FIELDS, "observed", "observed_low"])
    x = features(rows)
    total = export_model(train(rows, x, "total", "observed"), x)
    low = export_model(train(rows, x, "low", "observed_low"), x)
    OUTPUT.write_text(f"""// Generated by research/verification/build_cloud_calibration.py.
// Trained on {len(rows):,} matched IMS reports from {rows.time.min()[:10]} to {rows.time.max()[:10]}.

export type CloudNode = number | readonly [feature: number, threshold: number, left: number, right: number]
export interface CloudResidualModel {{
  bias: number
  trees: readonly (readonly CloudNode[])[]
}}

export const totalCloudModel: CloudResidualModel = {total}

export const lowCloudModel: CloudResidualModel = {low}
""", encoding="utf-8")
    print(f"Wrote {OUTPUT} from {len(rows):,} matched reports")


if __name__ == "__main__":
    main()
