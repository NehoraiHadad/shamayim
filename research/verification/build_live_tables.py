"""Tables for the Worker's live correction (worker/src/stations.ts).

Each IMS station's usual forecast error by season x standard-time hour, for the temperature blend the app uses on
day 0 (ICON 0.8, lead 0 archive series), shrunk toward the station's overall mean where data is thin. The Worker
subtracts it from the station's current error to get the anomaly: what the forecast is getting wrong *today*.
Also the station list (id, position, IMS region) for the regional "latest" requests.
The decay of the anomaly with hours ahead (LIVE_DECAY in the app) comes from results/live_lapse.json (gauss20).
"""
import json
import sys

import numpy as np
import pandas as pd

sys.argv = ["x"]
import build_correction as bc
import verify_temp as v

OUT = v.HERE.parent.parent / "worker" / "src" / "stations.ts"
SHRINK = 30  # hours


def main():
    df = bc.load()
    df["e"] = df["f_l0"] - df.td
    df = df.dropna(subset=["e"])
    st_mean = df.groupby("station_id").e.mean()
    g = df.groupby(["station_id", "season", "hour"]).e.agg(["sum", "count"])
    imsmeta = {s["stationId"]: s for s in json.load(open(v.HERE / "data" / "raw" / "ims" / "stations.json"))}
    rows = []
    for sid in sorted(st_mean.index):
        m = imsmeta.get(int(sid))
        if not m or not m.get("active") or int((df.station_id == sid).sum()) < 2000:
            continue
        tab = []
        for season in bc.SEASONS:
            row = []
            for h in range(24):
                if (sid, season, h) in g.index:
                    s, c = g.loc[(sid, season, h)]
                else:
                    s, c = 0.0, 0
                row.append((s + st_mean[sid] * SHRINK) / (c + SHRINK))
            tab.append(row)
        rows.append((int(sid), m["name"], m["location"]["latitude"], m["location"]["longitude"], m["regionId"], tab))
    lines = []
    for sid, name, lat, lon, region, tab in rows:
        t = ", ".join("[" + ", ".join(f"{x:.2f}" for x in r) + "]" for r in tab)
        lines.append(f"  {{ id: {sid}, name: {json.dumps(name)}, lat: {lat}, lon: {lon}, region: {region}, bias: [{t}] }},")
    OUT.write_text(f"""// Generated by research/verification/build_live_tables.py — do not edit by hand.
// IMS stations for the live correction, with each station's usual forecast error (forecast − observed, °C) for the
// app's day-0 temperature blend (ICON 0.8 / ECMWF 0.2), by season (winter, spring, summer, autumn) and hour of Israel
// standard time. From Open-Meteo's past forecasts against the station, {df.time.min():%Y-%m} to {df.time.max():%Y-%m}.

export interface Station {{
  id: number
  name: string
  lat: number
  lon: number
  /** IMS region whose "latest" request carries this station. */
  region: number
  bias: readonly (readonly number[])[]
}}

export const SEASON_CENTRE_DOY = [{", ".join(map(str, bc.CENTRE_DOY))}] as const

export const STATIONS: readonly Station[] = [
{chr(10).join(lines)}
]
""")
    print(len(rows), "stations ->", OUT, "regions", sorted({r[4] for r in rows}))


if __name__ == "__main__":
    main()
